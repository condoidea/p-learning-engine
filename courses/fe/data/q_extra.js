/* レッスンに紐づく追加の本番形式問題（o[0] が正解）
 * FE.addTo(レッスンID, 分野ID, 問題[]) … 問題を登録し、そのレッスンの解放対象に加える */
FE.addTo = function (lessonId, field, list) {
  var L = FE.lessonDefs[lessonId];
  list.forEach(function (q, i) {
    q.id = 'x-' + lessonId + '-' + (i + 1);
    q.f = field;
    FE.questions.push(q);
    L.q.push(q.id);
  });
};

